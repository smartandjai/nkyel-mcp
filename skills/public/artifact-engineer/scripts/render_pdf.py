"""PDF Renderer using Typst compiler: produces high-typography PDF and rendered page PNGs for Vision QA."""

from __future__ import annotations

import os
from pathlib import Path
from typing import Any
import typst

from document_spec import DocumentSpec, DocumentSection, TableData


def _typst_color(hex_str: str) -> str:
    """Format hex color into rgb(\"#...\") for Typst."""
    if not hex_str.startswith("#"):
        hex_str = f"#{hex_str}"
    return f'rgb("{hex_str}")'


def generate_typst_source(doc: DocumentSpec) -> str:
    """Generate professional Typst source code from DocumentSpec."""
    theme = doc.theme
    p_color = _typst_color(theme.primary_color)
    s_color = _typst_color(theme.secondary_color)
    t_color = _typst_color(theme.text_color)
    m_color = _typst_color(theme.muted_color)
    
    lines = [
        "// Auto-generated by Ñkyel Studio Professional Artifact Pipeline",
        f"#set page(paper: \"a4\", margin: (x: {theme.margin_cm}cm, top: 2.8cm, bottom: 2.5cm),",
        f"  header: context {{",
        f"    if here().page() > 1 [",
        f"      #grid(columns: (1fr, auto),",
        f"        align(left)[#text(size: 8pt, fill: {m_color})[{doc.title}]],",
        f"        align(right)[#text(size: 8pt, fill: {m_color})[{doc.organization}]]",
        f"      )",
        f"      #v(-3pt)",
        f"      #line(length: 100%, stroke: 0.5pt + {m_color})",
        f"    ]",
        f"  }},",
        f"  footer: context [",
        f"    #line(length: 100%, stroke: 0.5pt + {m_color})",
        f"    #v(-3pt)",
        f"    #grid(columns: (1fr, auto),",
        f"      align(left)[#text(size: 8pt, fill: {m_color})[Confidentiel · {doc.date}]],",
        f"      align(right)[#text(size: 8pt, fill: {m_color})[Page #here().page()]]",
        f"    )",
        f"  ]",
        ")",
        f"#set text(font: \"{theme.font_family_body}\", size: 10pt, fill: {t_color}, lang: \"{doc.language}\")",
        "#set par(justify: true, leading: 0.72em)",
        "",
        "// Title and Cover Block",
        "#align(center)[",
        f"  #v(2cm)",
        f"  #text(size: 24pt, weight: \"bold\", fill: {p_color})[{doc.title}] \\",
    ]

    if doc.subtitle:
        lines.append(f"  #v(0.3cm)")
        lines.append(f"  #text(size: 13pt, fill: {s_color})[{doc.subtitle}] \\")

    lines.extend([
        f"  #v(0.8cm)",
        f"  #text(size: 9.5pt, fill: {m_color})[Auteur : #strong[{doc.author}] · {doc.organization} · {doc.date}] \\",
        f"  #v(1.5cm)",
        "]",
        "",
    ])

    # Executive Summary Block
    if doc.executive_summary:
        lines.extend([
            f"#rect(width: 100%, fill: rgb(\"#f8fafc\"), stroke: 1pt + {s_color}, radius: 6pt, inset: 14pt)[",
            f"  #text(size: 11pt, weight: \"bold\", fill: {p_color})[Résumé Exécutif] \\",
            f"  #v(4pt)",
            f"  #text(size: 9.5pt, fill: {t_color})[{doc.executive_summary}]",
            "]",
            "#v(0.8cm)",
            "",
        ])

    # Sections
    for sec in doc.sections:
        if sec.page_break_before:
            lines.append("#pagebreak()")
        
        heading_prefix = "=" * sec.level
        lines.append(f"{heading_prefix} #text(fill: {p_color})[{sec.title}]")
        lines.append("#v(0.2cm)")

        # Key metrics grid if present
        if sec.key_metrics:
            cols = len(sec.key_metrics)
            lines.append(f"#grid(columns: {cols}, gutter: 12pt,")
            for m in sec.key_metrics:
                label = m.get("label", "")
                val = m.get("value", "")
                lines.append(f"  rect(width: 100%, fill: rgb(\"#f1f5f9\"), radius: 4pt, inset: 10pt)[")
                lines.append(f"    #align(center)[#text(size: 16pt, weight: \"bold\", fill: {s_color})[{val}] \\")
                lines.append(f"    #text(size: 8pt, fill: {m_color})[{label}]]")
                lines.append("  ],")
            lines.append(")")
            lines.append("#v(0.4cm)")

        # Paragraphs
        for p in sec.paragraphs:
            if p.style == "callout":
                lines.extend([
                    f"#rect(width: 100%, fill: rgb(\"#eff6ff\"), stroke: (left: 3pt + {s_color}), inset: 10pt)[",
                    f"  #text(size: 9pt)[{p.text}]",
                    "]",
                    "#v(0.3cm)",
                ])
            elif p.style == "bullet":
                lines.append(f"- {p.text}")
            elif p.style == "numbered":
                lines.append(f"+ {p.text}")
            else:
                lines.append(f"{p.text}")
                lines.append("#v(0.25cm)")

        # Tables
        for table in sec.tables:
            if table.title:
                lines.append(f"#text(weight: \"bold\", size: 10pt, fill: {p_color})[{table.title}]")
                lines.append("#v(0.15cm)")
            
            num_cols = len(table.columns) if table.columns else 1
            col_spec = ", ".join(["1fr"] * num_cols)
            lines.append(f"#table(")
            lines.append(f"  columns: ({col_spec}),")
            lines.append(f"  fill: (col, row) => if row == 0 {{ {p_color} }} else if calc.odd(row) {{ rgb(\"#f8fafc\") }} else {{ none }},")
            lines.append(f"  stroke: 0.3pt + rgb(\"#e2e8f0\"),")
            lines.append(f"  inset: 7pt,")
            
            # Header row
            for col in table.columns:
                lines.append(f"  table.header([#text(fill: white, weight: \"bold\", size: 9pt)[{col.header}]]),")
            
            # Data rows
            for row in table.rows:
                for col in table.columns:
                    val = str(row.get(col.key, ""))
                    align_fn = "left" if col.alignment == "left" else ("right" if col.alignment == "right" else "center")
                    lines.append(f"  align({align_fn})[#text(size: 8.5pt)[{val}]],")
            
            lines.append(")")
            if table.caption:
                lines.append(f"#align(center)[#text(size: 8pt, style: \"italic\", fill: {m_color})[{table.caption}]]")
            lines.append("#v(0.5cm)")

    # Citations & References
    if doc.citations:
        lines.append("#v(0.6cm)")
        lines.append(f"= #text(fill: {p_color})[Références & Sources]")
        lines.append("#v(0.2cm)")
        for idx, cit in enumerate(doc.citations, 1):
            url_str = f" (#link(\"{cit.url}\")[\"{cit.url}\"])" if cit.url else ""
            notes = f" — {cit.notes}" if cit.notes else ""
            lines.append(f"{idx}. #strong[{cit.title}]{notes}{url_str}")
            lines.append("#v(0.1cm)")

    return "\n".join(lines)


def render_pdf_and_pages(doc: DocumentSpec, output_dir: Path) -> dict[str, Any]:
    """Compile document into PDF and rendered page PNGs for vision inspection."""
    output_dir.mkdir(parents=True, exist_ok=True)
    
    typ_path = output_dir / f"{doc.document_id}.typ"
    pdf_path = output_dir / f"{doc.document_id}.pdf"
    preview_pattern = str(output_dir / f"{doc.document_id}_page_{{n}}.png")
    
    source = generate_typst_source(doc)
    with open(typ_path, "w", encoding="utf-8") as f:
        f.write(source)
    
    # 1. Compile PDF
    typst.compile(str(typ_path), output=str(pdf_path))
    
    # 2. Compile page images for DeepSeek Vision QA
    typst.compile(str(typ_path), output=preview_pattern)
    
    # Collect page images
    page_images = sorted(list(output_dir.glob(f"{doc.document_id}_page_*.png")))
    
    return {
        "pdf_path": str(pdf_path),
        "source_path": str(typ_path),
        "page_images": [str(p) for p in page_images],
        "page_count": len(page_images),
    }
